"""Golden values for the Rust port (idl-rs core, estimate::physics).

Writes core/tests/fixtures/physics_golden.json: the GT Force bike as fitted
(bikes/gt-force-fit.json, 4-bar from bikes/gt-force-linkage.json), a few
samples of inputs (q, q', q'' [13 each], w0, a0, f_meas [3 each]), the pod
readings the PyTorch model gives for them, and the exact Jacobian of those
readings with respect to the 45 local inputs, all in float64.

Readings per sample, 15 numbers: frame gyro (3), fork gyro (3), fork accel
(3), rear gyro (3), rear accel (3). Inputs, 45: q, q', q'', w0, a0 (the
solver's local-input order, gn.NZ); f_meas is held fixed.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import numpy as np  # noqa: E402
import torch  # noqa: E402

from idlml.bike.model import NL, pod_readings  # noqa: E402
from idlml.data.real import apply_fit, gt_force, load_fit  # noqa: E402

OUT = os.path.join(os.path.dirname(ROOT), "core", "tests", "fixtures", "physics_golden.json")


def main():
    torch.set_default_dtype(torch.float64)
    bike = apply_fit(gt_force(), load_fit()["values"]).double()
    fb = bike.linkage
    rng = np.random.default_rng(7)
    n = 6
    # latents of a plausible size: travel 0-160 mm, steer +-15 deg, small bending and flex
    q = np.c_[rng.uniform(0, 0.16, n), rng.uniform(-0.25, 0.25, n), rng.normal(0, 0.005, (n, 2)),
              rng.uniform(0, 0.15, n), rng.normal(0, 0.002, (n, 2)), rng.normal(0, 0.001, (n, 3)),
              rng.normal(0, 0.0003, (n, 3))]
    qd = q * 0 + rng.normal(0, 1, (n, NL)) * np.r_[1.5, 2, 0.5, 0.5, 1.5, 0.3, 0.3, [0.1] * 3, [0.03] * 3]
    qdd = rng.normal(0, 1, (n, NL)) * np.r_[150, 40, 80, 80, 150, 50, 50, [20] * 3, [5] * 3]
    w0, a0 = rng.normal(0, 1.5, (n, 3)), rng.normal(0, 30, (n, 3))
    fm = rng.normal(0, 6, (n, 3)) + np.r_[0, 0, 9.8]

    def readings(z, f):
        z = z[None]
        out = pod_readings(bike, z[:, :NL], z[:, NL:2 * NL], z[:, 2 * NL:3 * NL], z[:, 39:42], z[:, 42:45], f[None])
        return torch.cat([out["frame"][0], *out["fork"], *out["rear"]], 1)[0]

    samples = []
    for i in range(n):
        z = torch.tensor(np.r_[q[i], qd[i], qdd[i], w0[i], a0[i]])
        f = torch.tensor(fm[i])
        y = readings(z, f)
        j = torch.func.jacfwd(lambda zz: readings(zz, f))(z)  # forward mode, as the solver
        samples.append({"z": z.tolist(), "f_meas": f.tolist(), "readings": y.tolist(), "jacobian": j.tolist()})

    p = lambda t: t.detach().reshape(-1).tolist()
    side = {k: (fb.pts[k] - fb.imu0).tolist() for k in ("main_pivot", "horst", "ss_rocker", "rocker_frame")}
    doc = {
        "note": "generated by ml/experiments/export_golden.py; float64 PyTorch model",
        "bike": {
            "up": p(bike.up), "forward": p(bike.fwd), "steer_axis": p(bike.steer_axis), "steer_point": p(bike.steer_point),
            "fork_mount": p(bike.fork_mount), "fork_lever": p(bike.fork_lever), "bend_len": float(bike.bend_len),
            "bush_overlap": float(bike.bush_overlap), "rear_mount": p(bike.rear_mount), "rear_lever": p(bike.rear_lever),
            "link_scale": float(bike.link_scale), "mount_err_fork": p(bike.mount_err["fork"]),
            "mount_err_rear": p(bike.mount_err["rear"]),
            "linkage": {"side_rel_imu0": side, "coef": fb.coef.tolist(), "sign": float(fb.sign)},
        },
        "samples": samples,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=0)
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB")


if __name__ == "__main__":
    main()
