"""Golden window for the Rust solver (idl-rs core, estimate::physics::solve).

Writes core/tests/fixtures/physics_window.json: 2 s of the Beacon ride
(5790-5792 s, with a jump), the measurements, clip and airborne masks, bias
prior centres, the bike, the latent spec and weights, and the PyTorch
Gauss-Newton solution (latents per sample, biases, loss). The Rust solve of
the same inputs must land on the same latents.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import numpy as np  # noqa: E402
import torch  # noqa: E402

from idlml.data.cache import load  # noqa: E402
from idlml.data.real import apply_fit, gt_force, load_fit, window_objective  # noqa: E402
from idlml.factors.objective import Weights  # noqa: E402
from idlml.solve.batch import INIT, LEVELS, SCALE  # noqa: E402
from idlml.solve.gn import gauss_newton  # noqa: E402

OUT = os.path.join(os.path.dirname(ROOT), "core", "tests", "fixtures", "physics_window.json")


def main():
    d = load("173461a2")
    t = d["t"]
    sl = slice(int(np.searchsorted(t, 5790.0)), int(np.searchsorted(t, 5792.0)))
    w = Weights(gyro_sigma=0.05, accel_sigma=1.0, frame_accel_sigma=1.0)
    bike = apply_fit(gt_force(), load_fit()["values"])
    obj = window_objective(d, sl, bike, w, dev="cpu", air=True)  # CPU: leaves the GPU to long runs
    v, info = gauss_newton(obj, verbose=False)
    with torch.no_grad():
        q = obj.latents(v)[0].cpu().numpy()
    L = lambda x: np.asarray(x.detach().cpu() if torch.is_tensor(x) else x, dtype=np.float64).tolist()
    p = lambda x: x.detach().cpu().double().reshape(-1).tolist()
    fb = bike.linkage
    doc = {
        "note": "generated by ml/experiments/export_window.py",
        "rate": float(d["rate"]),
        "frame_gyro": L(obj.frame["gyro"]), "frame_accel": L(obj.frame["accel"]),
        "fork_gyro": L(obj.pods["fork"]["gyro"]), "fork_accel": L(obj.pods["fork"]["accel"]),
        "rear_gyro": L(obj.pods["rear"]["gyro"]), "rear_accel": L(obj.pods["rear"]["accel"]),
        "mask_fork": obj.pods["fork"]["mask"].cpu().numpy().tolist(), "mask_rear": obj.pods["rear"]["mask"].cpu().numpy().tolist(),
        "air": obj.air.cpu().numpy().tolist(),
        "bias_prior": {k: L(obj.prior[k][0]) for k in obj.globals},
        "levels": [[m, ix] for m, ix in LEVELS], "init": list(INIT), "scale": list(SCALE),
        "weights": {k: (list(x) if isinstance(x, tuple) else x) for k, x in vars(w).items()},
        "bike": {
            "up": p(bike.up), "forward": p(bike.fwd), "steer_axis": p(bike.steer_axis), "steer_point": p(bike.steer_point),
            "fork_mount": p(bike.fork_mount), "fork_lever": p(bike.fork_lever), "bend_len": float(bike.bend_len),
            "bush_overlap": float(bike.bush_overlap), "rear_mount": p(bike.rear_mount), "rear_lever": p(bike.rear_lever),
            "link_scale": float(bike.link_scale), "mount_err_fork": p(bike.mount_err["fork"]),
            "mount_err_rear": p(bike.mount_err["rear"]),
            "linkage": {"side_rel_imu0": {k: (fb.pts[k] - fb.imu0).tolist() for k in ("main_pivot", "horst", "ss_rocker", "rocker_frame")},
                        "coef": fb.coef.tolist(), "sign": float(fb.sign)},
        },
        "solution": {"q": q.tolist(), "globals": {k: L(v[k]) for k in obj.globals}, "loss": info["loss"][-1],
                     "iterations": info["iterations"]},
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, separators=(",", ":"))
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB; loss", round(info["loss"][-1], 2), "iterations", info["iterations"],
          "; air samples", int(obj.air.sum()), "; masked fork", int((~obj.pods["fork"]["mask"]).sum()))


if __name__ == "__main__":
    main()
